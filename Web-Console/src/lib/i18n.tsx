type ContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  dict: (typeof dictionaries)['zh'];
};

const LanguageContext = createContext<ContextValue | null>(null);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => {
    const stored = typeof window !== 'undefined' ? window.localStorage.getItem('hajime-language') : null;
    return stored === 'en' ? 'en' : 'zh';
  });

  useEffect(() => {
    window.localStorage.setItem('hajime-language', language);
    document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
  }, [language]);

  const value = useMemo(
    () => ({
      language,
      setLanguage,
      dict: dictionaries[language],
    }),
    [language],
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used inside LanguageProvider');
  }

  return context;
}
